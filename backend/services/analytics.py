"""Read-side aggregations for the console.

Aggregates are computed in Python over a narrow column projection. At the scale
this project targets (tens of thousands of rows per week) that is faster and more
portable than dialect-specific date bucketing. Results are cached for a few
seconds so several open consoles do not multiply database work.
"""

from __future__ import annotations

import json
import threading
import time
from collections import Counter, defaultdict
from datetime import datetime, timedelta
from typing import Any

from sqlalchemy import func

from backend.core.logging import get_logger
from backend.core.timeutil import parse_window, to_iso, utcnow
from backend.database import session_scope
from backend.models import Alert, Transaction
from backend.stream.pipeline import TransactionPipeline

logger = get_logger("sentinel.analytics")

_CACHE: dict[tuple, tuple[float, Any]] = {}
_CACHE_LOCK = threading.Lock()
# KPI snapshots can tolerate a few seconds of lag. Multi-day analytics scans a
# much larger row set, so keep that result longer and avoid re-running the same
# aggregation on every 20-second console refresh.
TTL_SECONDS = 30.0
ANALYTICS_TTL_SECONDS = 120.0

BUCKETS = {
    "1h": 5,
    "6h": 15,
    "24h": 60,
    "7d": 360,
    "30d": 1440,
}

RISK_BANDS = [
    ("0-24", 0, 24),
    ("25-49", 25, 49),
    ("50-74", 50, 74),
    ("75-100", 75, 100),
]


def _cache_key(name: str, window: str) -> tuple:
    return (name, window)


def _cache_get(key: tuple) -> Any | None:
    ttl = ANALYTICS_TTL_SECONDS if key[0] == "analytics" else TTL_SECONDS
    with _CACHE_LOCK:
        item = _CACHE.get(key)
        if item and time.monotonic() - item[0] < ttl:
            return item[1]
        if item:
            _CACHE.pop(key, None)
    return None


def _cache_set(key: tuple, value: Any) -> None:
    with _CACHE_LOCK:
        _CACHE[key] = (time.monotonic(), value)


def invalidate_cache() -> None:
    with _CACHE_LOCK:
        _CACHE.clear()


def _pct_change(current: float, previous: float) -> float | None:
    if previous <= 0:
        return None
    return round((current - previous) / previous * 100, 1)


def _labels(rows) -> dict[str, int]:
    labels = Counter()
    for row in rows:
        if row.label:
            labels[row.label] += 1
    return dict(labels)


def _metrics_from_counts(tp: int, fp: int, fn: int, tn: int) -> dict[str, Any] | None:
    total = tp + fp + fn + tn
    if total == 0:
        return None
    precision = tp / max(tp + fp, 1)
    recall = tp / max(tp + fn, 1)
    return {
        "flagged": tp + fp,
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "tn": tn,
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(2 * precision * recall / max(precision + recall, 1e-9), 4),
        "false_positive_rate": round(fp / max(fp + tn, 1), 4),
        "labelled_rows": total,
        "note": "Labels are generated by the synthetic data source.",
    }


def _label_metrics(rows) -> dict[str, Any] | None:
    tp = fp = fn = tn = 0
    for row in rows:
        if row.label not in {"fraud", "legit"}:
            continue
        flagged = row.decision in {"review", "block"}
        if row.label == "fraud" and flagged:
            tp += 1
        elif row.label == "fraud":
            fn += 1
        elif flagged:
            fp += 1
        else:
            tn += 1
    return _metrics_from_counts(tp, fp, fn, tn)


def _series_window(
    end: datetime, window: str, bucket_minutes: int
) -> tuple[datetime, datetime, int]:
    """Return a trailing window made of complete buckets.

    Including the in-progress bucket makes the latest point collapse toward zero
    and produces a misleading cliff at the right edge of every chart. The KPI
    cards still use the full rolling window; only the plotted series stops at the
    last boundary that has a complete interval of data.
    """
    span = parse_window(window)
    bucket = timedelta(minutes=bucket_minutes)
    floored_minute = (end.minute // bucket_minutes) * bucket_minutes
    series_end = end.replace(minute=floored_minute, second=0, microsecond=0)
    count = max(int(span.total_seconds() // bucket.total_seconds()), 1)
    series_start = series_end - bucket * count
    return series_start, series_end, count


def _bucket_series(rows, start: datetime, bucket_minutes: int, count: int) -> list[dict]:
    buckets = [
        {
            "t": to_iso(start + timedelta(minutes=bucket_minutes * index)),
            "total": 0,
            "blocked": 0,
            "review": 0,
            "fraud": 0,
        }
        for index in range(count)
    ]
    for row in rows:
        offset = int((row.created_at - start).total_seconds() // (bucket_minutes * 60))
        if offset < 0 or offset >= count:
            continue
        bucket = buckets[offset]
        bucket["total"] += 1
        if row.decision == "block":
            bucket["blocked"] += 1
        elif row.decision == "review":
            bucket["review"] += 1
        if row.label == "fraud":
            bucket["fraud"] += 1
    return buckets


def _risk_histogram(rows) -> list[dict]:
    bins = [0] * 10
    for row in rows:
        bins[min(int(row.risk_score // 10), 9)] += 1
    return [{"range": f"{index * 10}-{index * 10 + 9}", "count": bins[index]} for index in range(10)]


def build_overview(window: str, pipeline: TransactionPipeline) -> dict:
    key = _cache_key("overview", window)
    cached = _cache_get(key)
    if cached:
        # Aggregates are cached, runtime health is not. Injecting a fresh system
        # block keeps the latency and processed counters moving while the chart
        # data stays on its longer refresh interval.
        payload = dict(cached)
        payload["system"] = pipeline.system_status()
        return payload

    end = utcnow()
    span = parse_window(window)
    start = end - span
    previous_start = start - span
    bucket_minutes = BUCKETS.get(window, 60)
    series_start, series_end, series_count = _series_window(end, window, bucket_minutes)
    data_start = min(start, series_start)

    with session_scope() as session:
        all_current_rows = (
            session.query(
                Transaction.created_at,
                Transaction.amount,
                Transaction.risk_score,
                Transaction.model_score,
                Transaction.decision,
                Transaction.merchant_name,
                Transaction.merchant_category,
                Transaction.channel,
                Transaction.reason_codes,
                Transaction.label,
            )
            .filter(Transaction.created_at >= data_start)
            .all()
        )
        previous_rows = (
            session.query(
                Transaction.amount,
                Transaction.risk_score,
                Transaction.decision,
                Transaction.label,
            )
            .filter(Transaction.created_at >= previous_start, Transaction.created_at < start)
            .all()
        )

    current_rows = [row for row in all_current_rows if row.created_at >= start]
    reasons: Counter = Counter()
    merchants: dict[str, dict] = defaultdict(
        lambda: {"total": 0, "blocked": 0, "risk": 0, "volume": 0.0, "category": "general"}
    )
    channels: dict[str, dict] = defaultdict(lambda: {"total": 0, "blocked": 0, "risk": 0})
    bands = [0, 0, 0, 0]
    total = blocked = review = 0
    exposure = risk_sum = 0.0
    tp = fp = fn = tn = 0

    for row in current_rows:
        total += 1
        decision = row.decision
        if decision == "block":
            blocked += 1
            exposure += row.amount
        elif decision == "review":
            review += 1
        risk_sum += row.risk_score

        if row.label in {"fraud", "legit"}:
            flagged = decision in {"review", "block"}
            if row.label == "fraud" and flagged:
                tp += 1
            elif row.label == "fraud":
                fn += 1
            elif flagged:
                fp += 1
            else:
                tn += 1

        code_text = row.reason_codes
        if code_text and code_text != "[]":
            try:
                for reason in json.loads(code_text):
                    reasons[(reason.get("code"), reason.get("label"))] += 1
            except (TypeError, ValueError):
                pass

        merchant = merchants[row.merchant_name]
        merchant["total"] += 1
        merchant["blocked"] += 1 if decision == "block" else 0
        merchant["risk"] += row.risk_score
        merchant["volume"] += row.amount
        merchant["category"] = row.merchant_category
        channel = channels[row.channel]
        channel["total"] += 1
        channel["blocked"] += 1 if decision == "block" else 0
        channel["risk"] += row.risk_score

        score = row.risk_score
        if score <= 24:
            bands[0] += 1
        elif score <= 49:
            bands[1] += 1
        elif score <= 74:
            bands[2] += 1
        else:
            bands[3] += 1

    allow = total - blocked - review
    avg_risk = risk_sum / total if total else 0

    prev_total = len(previous_rows)
    prev_blocked = prev_review = 0
    prev_exposure = prev_risk = 0.0
    for row in previous_rows:
        if row.decision == "block":
            prev_blocked += 1
            prev_exposure += row.amount
        elif row.decision == "review":
            prev_review += 1
        prev_risk += row.risk_score
    prev_avg_risk = prev_risk / prev_total if prev_total else 0

    top_merchants = sorted(
        (
            {
                "name": name,
                "category": value["category"],
                "total": value["total"],
                "blocked": value["blocked"],
                "avg_risk": round(value["risk"] / max(value["total"], 1), 1),
                "volume": round(value["volume"], 2),
            }
            for name, value in merchants.items()
        ),
        key=lambda item: (item["blocked"], item["volume"]),
        reverse=True,
    )[:6]

    channel_rows = sorted(
        (
            {
                "channel": name,
                "total": value["total"],
                "blocked": value["blocked"],
                "avg_risk": round(value["risk"] / max(value["total"], 1), 1),
                "approval_rate": round((value["total"] - value["blocked"]) / max(value["total"], 1), 4),
            }
            for name, value in channels.items()
        ),
        key=lambda item: item["total"],
        reverse=True,
    )

    band_rows = [
        {
            "band": label,
            "count": bands[index],
            "share": round(bands[index] / total, 4) if total else 0,
        }
        for index, (label, _, _) in enumerate(RISK_BANDS)
    ]

    series = _bucket_series(all_current_rows, series_start, bucket_minutes, series_count)
    system = pipeline.system_status()

    payload = {
        "window": window,
        "generated_at": to_iso(end),
        "series_through": to_iso(series_end),
        "kpis": {
            "transactions": {
                "value": total,
                "previous": prev_total,
                "delta_pct": _pct_change(total, prev_total),
            },
            "blocked": {
                "value": blocked,
                "previous": prev_blocked,
                "delta_pct": _pct_change(blocked, prev_blocked),
            },
            "review": {
                "value": review,
                "previous": prev_review,
                "delta_pct": _pct_change(review, prev_review),
            },
            "exposure_prevented": {
                "value": round(exposure, 2),
                "previous": round(prev_exposure, 2),
                "delta_pct": _pct_change(exposure, prev_exposure),
            },
            "avg_risk": {
                "value": round(avg_risk, 1),
                "previous": round(prev_avg_risk, 1),
                "delta_pct": _pct_change(avg_risk, prev_avg_risk),
            },
            "approval_rate": {
                "value": round(allow / total, 4) if total else 0,
                "previous": round((prev_total - prev_blocked - prev_review) / prev_total, 4) if prev_total else 0,
                "delta_pct": None,
            },
        },
        "series": series,
        "risk_distribution": band_rows,
        "decisions": {
            "allow": allow,
            "review": review,
            "block": blocked,
            "block_rate": round(blocked / total, 4) if total else 0,
        },
        "top_reasons": [
            {"code": code, "label": label, "count": count}
            for (code, label), count in reasons.most_common(6)
        ],
        "top_merchants": top_merchants,
        "channels": channel_rows,
        "label_metrics": _metrics_from_counts(tp, fp, fn, tn),
        "system": system,
    }
    _cache_set(key, payload)
    return payload


def build_analytics(window: str, pipeline: TransactionPipeline) -> dict:
    key = _cache_key("analytics", window)
    cached = _cache_get(key)
    if cached:
        payload = dict(cached)
        payload["system"] = pipeline.system_status()
        return payload

    end = utcnow()
    span = parse_window(window)
    start = end - span
    drift_start = end - timedelta(days=7)
    bucket_minutes = BUCKETS.get(window, 60)
    series_start, series_end, series_count = _series_window(end, window, bucket_minutes)
    data_start = min(start, series_start)

    with session_scope() as session:
        all_rows = (
            session.query(
                Transaction.created_at,
                Transaction.amount,
                Transaction.risk_score,
                Transaction.model_score,
                Transaction.decision,
                Transaction.merchant_name,
                Transaction.merchant_category,
                Transaction.channel,
                Transaction.reason_codes,
                Transaction.label,
            )
            .filter(Transaction.created_at >= data_start)
            .all()
        )
        drift_rows = None
        if drift_start < data_start:
            drift_rows = (
                session.query(
                    Transaction.created_at,
                    Transaction.risk_score,
                    Transaction.model_score,
                    Transaction.decision,
                )
                .filter(Transaction.created_at >= drift_start)
                .all()
            )

    if drift_rows is None:
        drift_rows = [row for row in all_rows if row.created_at >= drift_start]

    rows = [row for row in all_rows if row.created_at >= start]
    by_day: dict[str, dict] = defaultdict(lambda: {"total": 0, "risk": 0.0, "model": 0.0, "blocked": 0})
    for row in drift_rows:
        day = row.created_at.date().isoformat()
        entry = by_day[day]
        entry["total"] += 1
        entry["risk"] += row.risk_score
        entry["model"] += row.model_score
        entry["blocked"] += 1 if row.decision == "block" else 0

    current_day = end.date().isoformat()
    drift = [
        {
            "date": day,
            "transactions": value["total"],
            "avg_risk": round(value["risk"] / max(value["total"], 1), 1),
            "avg_model_score": round(value["model"] / max(value["total"], 1), 1),
            "block_rate": round(value["blocked"] / max(value["total"], 1), 4),
        }
        for day, value in sorted(by_day.items())
        # The current UTC day is partial. Showing its first few hours next to
        # complete days makes a healthy model look like it fell off a cliff.
        if day < current_day
    ]

    reasons: Counter = Counter()
    category: dict[str, dict] = defaultdict(lambda: {"total": 0, "blocked": 0, "amount": 0.0})
    risk_bins = [0] * 10
    bands = [0, 0, 0, 0]
    labelled = 0
    tp = fp = fn = tn = 0

    for row in rows:
        score = row.risk_score
        risk_bins[min(int(score // 10), 9)] += 1
        if score <= 24:
            bands[0] += 1
        elif score <= 49:
            bands[1] += 1
        elif score <= 74:
            bands[2] += 1
        else:
            bands[3] += 1

        entry = category[row.merchant_category]
        entry["total"] += 1
        entry["blocked"] += 1 if row.decision == "block" else 0
        entry["amount"] += row.amount

        if row.label:
            labelled += 1
            if row.label in {"fraud", "legit"}:
                flagged = row.decision in {"review", "block"}
                if row.label == "fraud" and flagged:
                    tp += 1
                elif row.label == "fraud":
                    fn += 1
                elif flagged:
                    fp += 1
                else:
                    tn += 1

        code_text = row.reason_codes
        if code_text and code_text != "[]":
            try:
                for reason in json.loads(code_text):
                    reasons[(reason.get("code"), reason.get("label"))] += 1
            except (TypeError, ValueError):
                pass

    payload = {
        "window": window,
        "generated_at": to_iso(end),
        "series_through": to_iso(series_end),
        "series": _bucket_series(all_rows, series_start, bucket_minutes, series_count),
        "risk_histogram": [
            {"range": f"{index * 10}-{index * 10 + 9}", "count": risk_bins[index]}
            for index in range(10)
        ],
        "risk_distribution": [
            {"band": label, "count": bands[index]}
            for index, (label, _, _) in enumerate(RISK_BANDS)
        ],
        "top_reasons": [
            {
                "code": code,
                "label": label,
                "count": count,
                "share": round(count / max(len(rows), 1), 4),
            }
            for (code, label), count in reasons.most_common(10)
        ],
        "categories": sorted(
            (
                {
                    "category": name,
                    "total": value["total"],
                    "blocked": value["blocked"],
                    "volume": round(value["amount"], 2),
                    "block_rate": round(value["blocked"] / max(value["total"], 1), 4),
                }
                for name, value in category.items()
            ),
            key=lambda item: item["volume"],
            reverse=True,
        )[:8],
        "model_drift": drift,
        "label_metrics": _metrics_from_counts(tp, fp, fn, tn),
        "coverage": {
            "transactions": len(rows),
            "labelled": labelled,
            "window": window,
        },
        "system": pipeline.system_status(),
    }
    _cache_set(key, payload)
    return payload


def warm(pipeline: TransactionPipeline) -> None:
    """Populate the two first-screen aggregates while ingestion is paused.

    The analytics page scans every row in the selected window. Doing that on the
    first HTTP request makes the initial page load slow and lets the aggregation
    compete with live scoring for the GIL. Warming the default views after a
    backfill keeps the first visit fast without changing the data.
    """
    for window in ("24h",):
        try:
            build_overview(window, pipeline)
        except Exception as exc:  # a cold cache must never fail the seed
            logger.warning("overview warm-up failed for %s: %s", window, exc)
    try:
        build_analytics("7d", pipeline)
    except Exception as exc:
        logger.warning("analytics warm-up failed: %s", exc)


def alert_stats() -> dict:
    now = utcnow()
    with session_scope() as session:
        status_rows = session.query(Alert.status, func.count(Alert.id)).group_by(Alert.status).all()
        severity_rows = session.query(Alert.severity, func.count(Alert.id)).group_by(Alert.severity).all()
        open_critical = (
            session.query(func.count(Alert.id))
            .filter(Alert.status.in_(["open", "investigating"]), Alert.severity == "critical")
            .scalar()
            or 0
        )
        resolved_24h = (
            session.query(func.count(Alert.id))
            .filter(Alert.resolved_at >= now - timedelta(hours=24))
            .scalar()
            or 0
        )
        oldest = (
            session.query(func.min(Alert.created_at))
            .filter(Alert.status.in_(["open", "investigating"]))
            .scalar()
        )
        total = session.query(func.count(Alert.id)).scalar() or 0

    oldest_minutes = int((now - oldest).total_seconds() / 60) if oldest else 0
    by_status = {status: count for status, count in status_rows}
    return {
        "total": total,
        "by_status": by_status,
        "by_severity": {severity: count for severity, count in severity_rows},
        "open": by_status.get("open", 0),
        "investigating": by_status.get("investigating", 0),
        "resolved": by_status.get("resolved", 0),
        "false_positive": by_status.get("false_positive", 0),
        "open_critical": open_critical,
        "resolved_24h": resolved_24h,
        "oldest_open_minutes": oldest_minutes,
    }

